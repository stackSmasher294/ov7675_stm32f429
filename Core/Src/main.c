void draw_moving_squares(int window_height, int window_width, uint32_t *frameBuffer)
{
    static int offset = 0;
    uint32_t argb = 0;
    uint8_t* p_argb = (uint8_t*)&argb;
    uint8_t a = 255,r,g,b;
    for (int y = 0; y < window_height; y++)
    {
        for (int x = 0; x < window_width; x++)
        {

          r = (x + offset) % 128;
          g = (y + offset) % 128;
          b = 128;
          p_argb[0] = r;
          p_argb[1] = g;
          p_argb[2] = b;
          p_argb[3] = a;
          frameBuffer[y * window_width + x] = argb;
        }
    }
  offset++;
}

